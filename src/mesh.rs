    fn one_corner_case_has_one_triangle() {
        let mut data = vec![0u8; 8];
        data[0] = 1;
        let volume = BinaryVolume::new(data, 2, 2, 2).unwrap();
        let mesh = marching_cubes(&volume, [1.0; 3]);
        assert_eq!(mesh.triangles.len(), 1);
        assert_eq!(mesh.vertices.len(), 3);
        let expected = 3.0_f64.sqrt() / 8.0;
        assert!((mesh.surface_area() - expected).abs() < 1e-12);

        // The foreground corner is at the origin. The triangle centroid lies
        // toward +x,+y,+z, so an outward normal must have positive dot product
        // with that displacement.
        let [a, b, c] = mesh.triangles[0];
        let pa = mesh.vertices[a];
        let pb = mesh.vertices[b];
        let pc = mesh.vertices[c];
        let normal = cross(sub(pb, pa), sub(pc, pa));
        let centroid = [
            (pa[0] + pb[0] + pc[0]) / 3.0,
            (pa[1] + pb[1] + pc[1]) / 3.0,
            (pa[2] + pb[2] + pc[2]) / 3.0,
        ];
        assert!(dot(normal, centroid) > 0.0);
    }
