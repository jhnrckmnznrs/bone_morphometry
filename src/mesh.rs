#[derive(Clone, Debug)]
pub struct Mesh {
    pub vertices: Vec<[f64; 3]>,
    pub triangles: Vec<[usize; 3]>,
}

impl Mesh {
    pub fn surface_area(&self) -> f64 {
        self.triangles
            .iter()
            .map(|&[a, b, c]| triangle_area(self.vertices[a], self.vertices[b], self.vertices[c]))
            .sum()
    }
}

#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
struct EdgeKey {
    a: [isize; 3],
    b: [isize; 3],
}

impl EdgeKey {
    #[inline]
    fn new(a: [isize; 3], b: [isize; 3]) -> Self {
        if a <= b {
            Self { a, b }
        } else {
            Self { a: b, b: a }
        }
    }
}

