/// Midpoint binary-surface reference mesh. Production curvature
/// uses `marching_cubes_scalar` on the smoothed SDF.
#[allow(dead_code)]
pub fn marching_cubes(volume: &BinaryVolume, spacing: [f64; 3]) -> Mesh {
    let mut vertices = Vec::<[f64; 3]>::new();
    let mut triangles = Vec::<[usize; 3]>::new();
    let mut edge_vertices = HashMap::<EdgeKey, usize>::new();

    for z in 0..(volume.depth - 1) {
        for y in 0..(volume.height - 1) {
            for x in 0..(volume.width - 1) {
                let mut case_index = 0usize;
                for (i, &[dx, dy, dz]) in CUBE_VERTICES.iter().enumerate() {
                    if volume.get(x + dx, y + dy, z + dz) != 0 {
                        case_index |= 1usize << i;
                    }
                }
                if case_index == 0 || case_index == 255 {
                    continue;
                }

                let row = &TRI_TABLE[case_index];
                let mut i = 0usize;
                while i + 2 < row.len() && row[i] >= 0 {
                    let mut tri_idx = [0usize; 3];
                    for corner in 0..3 {
                        tri_idx[corner] = vertex_for_edge(
                            x,
                            y,
                            z,
                            row[i + corner] as usize,
                            spacing,
                            &mut vertices,
                            &mut edge_vertices,
                        );
                    }
                    if tri_idx[0] != tri_idx[1]
                        && tri_idx[1] != tri_idx[2]
                        && tri_idx[0] != tri_idx[2]
                    {
                        // The classic table with foreground bits set is
                        // inward-oriented for this scalar convention. Reverse
                        // the experimental midpoint mesh so curvature normals
                        // point outward from foreground bone into background.
                        triangles.push([tri_idx[0], tri_idx[2], tri_idx[1]]);
                    }
                    i += 3;
                }
            }
        }
    }

    Mesh {
        vertices,
        triangles,
    }
}


/// Classic marching cubes for a scalar field at an arbitrary isovalue.
///
/// `values` are stored in ordinary z/y/x row-major order, with physical
/// coordinates obtained by multiplying grid coordinates by `spacing`.
/// Vertices are linearly interpolated along crossing grid edges. The classic
/// table is oriented for the positive-inside convention and reversed so that
/// triangle normals point from positive values toward negative values.
pub fn marching_cubes_scalar(
    values: &[f64],
    width: usize,
    height: usize,
    depth: usize,
    spacing: [f64; 3],
    isovalue: f64,
) -> Mesh {
    assert_eq!(values.len(), width * height * depth);
    if width < 2 || height < 2 || depth < 2 {
        return Mesh {
            vertices: Vec::new(),
            triangles: Vec::new(),
        };
    }

    let mut vertices = Vec::<[f64; 3]>::new();
    let mut triangles = Vec::<[usize; 3]>::new();
    let mut edge_vertices = HashMap::<EdgeKey, usize>::new();

    #[inline(always)]
    fn index(x: usize, y: usize, z: usize, width: usize, height: usize) -> usize {
        (z * height + y) * width + x
    }

    for z in 0..(depth - 1) {
        for y in 0..(height - 1) {
            for x in 0..(width - 1) {
                let mut case_index = 0usize;
                let mut cube_values = [0.0f64; 8];
                for (i, &[dx, dy, dz]) in CUBE_VERTICES.iter().enumerate() {
                    let value = values[index(x + dx, y + dy, z + dz, width, height)];
                    cube_values[i] = value;
                    if value > isovalue {
                        case_index |= 1usize << i;
                    }
                }
                if case_index == 0 || case_index == 255 {
                    continue;
                }

                let row = &TRI_TABLE[case_index];
                let mut i = 0usize;
                while i + 2 < row.len() && row[i] >= 0 {
                    let mut tri_idx = [0usize; 3];
                    for corner in 0..3 {
                        let edge = row[i + corner] as usize;
                        let [ca, cb] = EDGE_VERTICES[edge];
                        let va = cube_values[ca];
                        let vb = cube_values[cb];
                        let da = CUBE_VERTICES[ca];
                        let db = CUBE_VERTICES[cb];
                        let a = [
                            (x + da[0]) as isize,
                            (y + da[1]) as isize,
                            (z + da[2]) as isize,
                        ];
                        let b = [
                            (x + db[0]) as isize,
                            (y + db[1]) as isize,
                            (z + db[2]) as isize,
                        ];
                        let key = EdgeKey::new(a, b);
                        tri_idx[corner] = *edge_vertices.entry(key).or_insert_with(|| {
                            let denom = vb - va;
                            let t = if denom.abs() <= f64::EPSILON {
                                0.5
                            } else {
                                ((isovalue - va) / denom).clamp(0.0, 1.0)
                            };
                            let gx = a[0] as f64 + t * (b[0] - a[0]) as f64;
                            let gy = a[1] as f64 + t * (b[1] - a[1]) as f64;
                            let gz = a[2] as f64 + t * (b[2] - a[2]) as f64;
                            let id = vertices.len();
                            vertices.push([
                                gx * spacing[0],
                                gy * spacing[1],
                                gz * spacing[2],
                            ]);
                            id
                        });
                    }

                    if tri_idx[0] != tri_idx[1]
                        && tri_idx[1] != tri_idx[2]
                        && tri_idx[0] != tri_idx[2]
                    {
                        triangles.push([tri_idx[0], tri_idx[2], tri_idx[1]]);
                    }
                    i += 3;
                }
            }
        }
    }

    Mesh {
        vertices,
        triangles,
    }
}

/// Reproduce the Boolean marching-cubes convention used by BoneJ2 Surface Area.
///
/// BoneJ2 delegates mesh creation to ImageJ-Ops `DefaultMarchingCubes`, which:
/// - extends the binary image with `false` outside the stack;
/// - scans cubes that straddle the original image boundary;
/// - uses the ImageJ lookup-cube vertex ordering;
/// - has Boolean values 0/1 with default isolevel 1; and
/// - therefore places each crossing at the foreground (value-1) endpoint.
///
/// The returned coordinates are converted directly to physical coordinates
/// using `spacing`. For the isotropic microCT inputs used in the validation
/// cohort this is equivalent to BoneJ's final uniform area scaling.
pub fn marching_cubes_bonej(volume: &BinaryVolume, spacing: [f64; 3]) -> Mesh {
    let mut vertices = Vec::<[f64; 3]>::new();
    let mut triangles = Vec::<[usize; 3]>::new();
    let mut edge_vertices = HashMap::<EdgeKey, usize>::new();

    // ImageJ scans cursor positions from min-1 through max+1. The terminal
    // all-background layer cannot emit triangles, so scanning lower cube
    // corners through max is sufficient while preserving every boundary case.
    for z in -1isize..volume.depth as isize {
        for y in -1isize..volume.height as isize {
            for x in -1isize..volume.width as isize {
                let mut case_index = 0usize;
                for (i, &[dx, dy, dz]) in IMAGEJ_CUBE_VERTICES.iter().enumerate() {
                    // ImageJ sets a lookup bit when vertex_value < isolevel.
                    // With Boolean values and isolevel 1, background (0) sets
                    // the bit and foreground (1) clears it.
                    if !volume.get_signed(x + dx, y + dy, z + dz) {
                        case_index |= 1usize << i;
                    }
                }
                if case_index == 0 || case_index == 255 {
                    continue;
                }

                let row = &TRI_TABLE[case_index];
                let mut i = 0usize;
                while i + 2 < row.len() && row[i] >= 0 {
                    // ImageJ reverses the triangle-table vertex order when
                    // adding a facet. Orientation does not affect area, but we
                    // mirror it here for implementation fidelity.
                    let edges = [
                        row[i + 2] as usize,
                        row[i + 1] as usize,
                        row[i] as usize,
                    ];
                    let mut tri_idx = [0usize; 3];
                    for corner in 0..3 {
                        tri_idx[corner] = vertex_for_edge_bonej(
                            volume,
                            [x, y, z],
                            edges[corner],
                            spacing,
                            &mut vertices,
                            &mut edge_vertices,
                        );
                    }

                    // ImageJ's positiveArea check rejects triangles whose
                    // endpoint interpolation collapses them to zero area.
                    if tri_idx[0] != tri_idx[1]
                        && tri_idx[1] != tri_idx[2]
                        && tri_idx[0] != tri_idx[2]
                        && triangle_area(
                            vertices[tri_idx[0]],
                            vertices[tri_idx[1]],
                            vertices[tri_idx[2]],
                        ) > 0.0
                    {
                        triangles.push(tri_idx);
                    }
                    i += 3;
                }
            }
        }
    }

    Mesh {
        vertices,
        triangles,
    }
}

fn vertex_for_edge_bonej(
    volume: &BinaryVolume,
    origin: [isize; 3],
    edge: usize,
    spacing: [f64; 3],
    vertices: &mut Vec<[f64; 3]>,
    cache: &mut HashMap<EdgeKey, usize>,
) -> usize {
    let [x, y, z] = origin;
    let [va, vb] = EDGE_VERTICES[edge];
    let a_local = IMAGEJ_CUBE_VERTICES[va];
    let b_local = IMAGEJ_CUBE_VERTICES[vb];
    let a = [x + a_local[0], y + a_local[1], z + a_local[2]];
    let b = [x + b_local[0], y + b_local[1], z + b_local[2]];
    let key = EdgeKey::new(a, b);
    if let Some(&index) = cache.get(&key) {
        return index;
    }

    let a_foreground = volume.get_signed(a[0], a[1], a[2]);
    let b_foreground = volume.get_signed(b[0], b[1], b[2]);
    debug_assert_ne!(a_foreground, b_foreground);

    // DefaultVertexInterpolator at isolevel 1 returns the endpoint whose
    // Boolean scalar value is exactly 1.
    let p = if a_foreground { a } else { b };
    let point = [
        p[0] as f64 * spacing[0],
        p[1] as f64 * spacing[1],
        p[2] as f64 * spacing[2],
    ];
    let index = vertices.len();
    vertices.push(point);
    cache.insert(key, index);
    index
}

fn vertex_for_edge(
    x: usize,
    y: usize,
    z: usize,
    edge: usize,
    spacing: [f64; 3],
    vertices: &mut Vec<[f64; 3]>,
    cache: &mut HashMap<EdgeKey, usize>,
) -> usize {
    let [va, vb] = EDGE_VERTICES[edge];
    let a_local = CUBE_VERTICES[va];
    let b_local = CUBE_VERTICES[vb];
    let a = [x + a_local[0], y + a_local[1], z + a_local[2]];
    let b = [x + b_local[0], y + b_local[1], z + b_local[2]];
    let key = EdgeKey::new(
        [a[0] as isize, a[1] as isize, a[2] as isize],
        [b[0] as isize, b[1] as isize, b[2] as isize],
    );
    if let Some(&index) = cache.get(&key) {
        return index;
    }

    let point = [
        0.5 * (a[0] + b[0]) as f64 * spacing[0],
        0.5 * (a[1] + b[1]) as f64 * spacing[1],
        0.5 * (a[2] + b[2]) as f64 * spacing[2],
    ];
    let index = vertices.len();
    vertices.push(point);
    cache.insert(key, index);
    index
}

#[inline]
pub fn triangle_area(a: [f64; 3], b: [f64; 3], c: [f64; 3]) -> f64 {
    let ab = sub(b, a);
    let ac = sub(c, a);
    0.5 * norm(cross(ab, ac))
}

#[inline]
pub(crate) fn sub(a: [f64; 3], b: [f64; 3]) -> [f64; 3] {
    [a[0] - b[0], a[1] - b[1], a[2] - b[2]]
}

#[inline]
pub(crate) fn scale(a: [f64; 3], s: f64) -> [f64; 3] {
    [a[0] * s, a[1] * s, a[2] * s]
}

#[inline]
pub(crate) fn dot(a: [f64; 3], b: [f64; 3]) -> f64 {
    a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
}

#[inline]
pub(crate) fn cross(a: [f64; 3], b: [f64; 3]) -> [f64; 3] {
    [
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    ]
}

#[inline]
pub(crate) fn norm(a: [f64; 3]) -> f64 {
    dot(a, a).sqrt()
}

#[inline]
pub(crate) fn normalize(a: [f64; 3]) -> [f64; 3] {
    let n = norm(a);
    if n > 0.0 {
        scale(a, 1.0 / n)
    } else {
        [0.0, 0.0, 0.0]
    }
}

